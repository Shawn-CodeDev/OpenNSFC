/** 按标识取参数；支持中文别名，便于人读与命令行传入 */
export function getTrack(name) {
  if (!name) return TRACKS.youth;
  const n = String(name).trim().toLowerCase();
  if (['youth', 'qingnian', '青年', '青年c类', '青年c', 'c'].includes(n)) return TRACKS.youth;
  if (['general', 'mianshang', '面上', '面上项目'].includes(n)) return TRACKS.general;
  throw new Error(`未知申报类型「${name}」。可用值：youth（青年C类）/ general（面上项目）`);
}

/** 生成官方提纲纯文本（供 check-template.mjs 与人工核对使用） */
export function renderOutline(track) {
  const out = [
    '报告正文（2026版）',
    '参照以下提纲撰写，要求内容翔实、清晰，层次分明，标题突出。',
    '申请书正文原则上不超过30页，鼓励简洁表达。',
    '请勿删除或改动下述提纲标题及括号中的文字。',
  ];
  for (const it of track.items) {
    out.push(it.text);
    if (it.paren) out.push(it.paren.replace(/^（|）$/g, ''));
  }
  return out.join('\n') + '\n';
}

/** 两类的差异摘要（供文档与自检输出） */
export function diffSummary() {
  return TRACKS.general.items
    .filter((g) => g.diff)
    .map((g) => {
      const y = TRACKS.youth.items.find((i) => i.key === g.key);
      return { key: g.key, youth: y.text, general: g.text };
    });
}
